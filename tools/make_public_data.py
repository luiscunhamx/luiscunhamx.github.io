# Funding summary: only totals and counts are written (data/funding_summary.yml);
# per-project amounts stay in the private workbook.
import re
# ECB annual average reference rates (EUR per unit), used to convert non-euro awards
# by the start year of the grant. Converted totals are shown as approximate.
EUR_PER = {'GBP': {2011: 1.1522, 2015: 1.3777, 2017: 1.1407, 2019: 1.1393},
           'USD': {2016: 0.9034, 2019: 0.8933}}
UK_FUNDERS = ('NERC', 'STFC', 'USW')

def _year(s):
    m = re.search(r'(19|20)\d\d', str(s)); return int(m.group()) if m else None

def _amount(v, funder, year):
    """Return (euros, approximate?) or (None, False)."""
    if v is None: return None, False
    if isinstance(v, (int, float)):
        val, cur, approx = float(v), 'EUR', False
    else:
        t = str(v).strip()
        if t in EMPTY or not re.search(r'\d', t): return None, False
        approx = '~' in t
        cur = 'USD' if '$' in t else ('GBP' if '£' in t else 'EUR')
        mult = 1e6 if re.search(r'\dM\b', t, re.I) else 1
        val = float(re.sub(r'[^\d.]', '', t.replace(',', ''))) * mult
    if cur == 'EUR' and any(k in str(funder) for k in UK_FUNDERS):
        cur = 'GBP'  # UK grants are recorded without a currency sign
    if cur != 'EUR':
        rates = EUR_PER[cur]
        rate = rates.get(year) or rates[min(rates, key=lambda y: abs(y - (year or y)))]
        return val * rate, True
    return val, approx

def _funder_group(f):
    f = str(f)
    if any(k in f for k in ('Horizon', 'H2020', 'MSCA', 'COST')): return 'EU Horizon programmes'
    if 'EFSA' in f: return 'EFSA'
    if 'Biodiversa' in f: return 'Biodiversa+'
    if any(k in f for k in ('FCT', 'PRR', 'Portugal 2020', 'CCDRC', 'COMPETE', 'Azores')): return 'Portuguese national and regional'
    if any(k in f for k in UK_FUNDERS): return 'UK research councils and universities'
    return 'Foundations and other'

def funding_summary(wb):
    rows = list(wb['Projects'].iter_rows(values_only=True))
    head = [str(h).strip() if h else '' for h in rows[0]]
    i = {k: head.index(k) for k in ('Years', 'Project', 'Role', 'Funding Source (Reference)', 'Total Funding', 'UC Funding')}
    n = n_lead = n_known = 0; total = secured = 0.0; approx = False
    secured_names, by_funder, by_role = [], {}, {}
    for r in rows[1:]:
        name = clean(r[i['Project']]) if i['Project'] < len(r) else None
        if not name or 'Back_to' in str(r[0]): continue
        n += 1
        role, funder, year = str(r[i['Role']] or ''), r[i['Funding Source (Reference)']], _year(r[i['Years']])
        lead = bool(re.match(r'\s*(PI|WP Leader|Co-I)', role))
        n_lead += lead
        grp = _funder_group(funder); by_funder[grp] = by_funder.get(grp, 0) + 1
        rk = 'PI, Co-I or WP leader' if lead else 'Researcher or team member'
        by_role[rk] = by_role.get(rk, 0) + 1
        t, ta = _amount(r[i['Total Funding']], funder, year)
        if t: total += t; n_known += 1; approx |= ta
        if re.search(r'\bPI\b|Coordinator', role):
            u, ua = _amount(r[i['UC Funding']], funder, year)
            if u:
                secured += u; approx |= ua
                short = name.split(' – ')[0].split(' - ')[0].split(':')[0].strip()
                if 'Scientific Employment' in str(funder): short = f'FCT CEEC ({short})'
                secured_names.append(short)
    out = {'projects': n, 'projects_lead': n_lead,
           'secured_uc_as_pi_or_coordinator_eur': round(secured), 'secured_projects': secured_names,
           'combined_budget_eur': round(total), 'combined_budget_projects_with_known_budget': n_known,
           'approximate': approx, 'by_funder': dict(sorted(by_funder.items(), key=lambda x: -x[1])),
           'by_role': by_role}
    with open('data/funding_summary.yml', 'w', encoding='utf-8') as f:
        f.write('# Generated by tools/make_public_data.py: totals and counts only (no per-project amounts). Do not edit.\n')
        f.write('# Non-euro awards converted at ECB annual average rates for the start year (approximate).\n')
        yaml.safe_dump(out, f, allow_unicode=True, sort_keys=False, width=1000)
    print(f"funding summary: {n} projects, secured as PI/coordinator €{secured:,.0f}, combined budget €{total:,.0f} ({n_known} with known budget)")

if __name__ == '__main__':
    main(sys.argv[1])
