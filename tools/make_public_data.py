"""Copy the public part of the private CV workbook into data/*.yml.

Usage: python tools/make_public_data.py PATH/TO/cv.xlsx

Only the sheets and columns listed in PUBLIC are copied. Everything else in the
workbook (referees, non-approved projects, external services, annex lists,
funding amounts, notes, Pending_Communications) stays private.
Cells marked [TO CONFIRM] are left out and never reaches this repository.
"""
import sys, os, datetime
import openpyxl, yaml

PUBLIC = {  # output file: (sheet, {column in workbook: key in yml})
    'experience':  ('Professional_Experience', {'Position / Title': 'position', 'Institution / Location': 'institution', 'Period': 'period'}),
    'education':   ('Education', {'Degree': 'degree', 'Years': 'years', 'Institution': 'institution', 'Thesis Title': 'thesis', 'Link': 'link', 'Honours': 'honours'}),
    'memberships': ('Memberships', {'Organization / Network': 'organisation', 'Role / Status': 'role', 'Since': 'since'}),
    'distinctions':('Distinctions', {'Year': 'year', 'Title': 'title', 'Institution / Awarding Body': 'body', 'Country': 'country'}),
    'roles':       ('Management&Coordination_Roles', {'Period': 'period', 'Role': 'role', 'Unit/Institution': 'unit', 'Details/Link': 'link'}),
    'languages':   ('Other_Skills', {'Skill / Certification': 'skill', 'Level / Details': 'level'}),
    'publications':('Publications', {'Year': 'year', 'Authors (normalized)': 'authors', 'Title': 'title', 'Journal/Book': 'venue', 'Volume': 'volume', 'Issue': 'issue', 'Pages': 'pages', 'DOI': 'doi'}),
    'chapters':    ('Chapters', {'Year': 'year', 'Authors (normalized)': 'authors', 'Title': 'title', 'Journal/Book': 'venue', 'Pages': 'pages', 'DOI': 'doi'}),
    'preprints':   ('Preprints', {'Year': 'year', 'Authors (normalized)': 'authors', 'Title': 'title', 'Platform': 'venue', 'DOI': 'doi'}),
    'reports':     ('Technical_Publications', {'Year': 'year', 'Authors': 'authors', 'Title': 'title', 'Commissioning body / Venue': 'venue', 'DOI/URL': 'link'}),
    'projects':    ('Projects', {'Years': 'years', 'Project': 'project', 'Role': 'role', 'Principal Investigator': 'pi', 'Responsible Institution': 'institution', 'Funding Source (Reference)': 'funder'}),
    'talks':       ('Invited_Oral_Presentations', {'Year': 'year', 'Title': 'title', 'Event / Conference': 'event', 'Location': 'location', 'URL / DOI': 'link'}),
    'orals':       ('Oral_Presentations', {'Year': 'year', 'Title': 'title', 'Authors': 'authors', 'Event / Conference': 'event', 'Location': 'location', 'URL / DOI': 'link'}),
    'posters':     ('Posters', {'Year': 'year', 'Title': 'title', 'Authors': 'authors', 'Event / Conference': 'event', 'Location': 'location', 'URL / DOI': 'link'}),
    'teaching':    ('Teaching', {'Academic Year': 'year', 'Institution': 'institution', 'Title': 'title', 'Course(s)': 'courses', 'Hours': 'hours'}),
    'supervision_phd': ('PhD&Postdoc_Supervisions&Tech', {'Level': 'level', 'Author': 'name', 'Title': 'title', 'Degree/Field': 'degree', 'Institution/Department': 'institution', 'Years': 'years', 'Role': 'role'}),
    'supervision_other': ('Other_Supervision', {'Level': 'level', 'Author': 'name', 'Title': 'title', 'Degree/Field': 'degree', 'Institution/Department': 'institution', 'Years': 'years', 'Role': 'role'}),
    'outreach':    ('Outreach_Activities', {'Title': 'title', 'Source': 'source', 'Link': 'link'}),
}
EMPTY = (None, '', 'NA', 'Na', 'na', '–', '-')

def clean(v):
    if isinstance(v, datetime.datetime): return v.strftime('%Y-%m')
    if isinstance(v, float) and v.is_integer(): v = int(v)
    v = str(v).strip() if v not in EMPTY else None
    if v and 'TO CONFIRM' in v: return None  # unconfirmed values stay private
    return None if v in EMPTY else v

def main(path):
    wb = openpyxl.load_workbook(path, read_only=True, data_only=True)
    os.makedirs('data', exist_ok=True)
    for out, (sheet, cols) in PUBLIC.items():
        rows = list(wb[sheet].iter_rows(values_only=True))
        head = [str(h).strip() if h else '' for h in rows[0]]
        idx = {k: head.index(c) for c, k in cols.items() if c in head}
        missing = [c for c in cols if c not in head]
        if missing: print(f'warning: {sheet}: columns not found: {missing}')
        recs = []
        for r in rows[1:]:
            rec = {k: clean(r[i]) for k, i in idx.items() if i < len(r)}
            rec = {k: v for k, v in rec.items() if v}
            if len(rec) >= 2: recs.append(rec)
        with open(f'data/{out}.yml', 'w', encoding='utf-8') as f:
            f.write(f'# Generated by tools/make_public_data.py from the private CV workbook (sheet "{sheet}"). Do not edit.\n')
            yaml.safe_dump(recs, f, allow_unicode=True, sort_keys=False, width=1000)
        print(f'{out}: {len(recs)} records')

if __name__ == '__main__':
    main(sys.argv[1])
