# Teaching & supervision panel (counts only, all from data/teaching.yml and data/supervision_*.yml).
import datetime
def yend(s): ys = re.findall(r'(?:19|20)\d\d', str(s)); return int(ys[-1]) if ys else 0
def ongoing(r):  # ongoing if planned, open-ended, or ending after the current year
    y = str(r.get('years', '')).lower()
    return 'planned' in y or 'present' in y or yend(y) > datetime.date.today().year
def hrs(t):
    try: return float(t.get('hours') or 0)
    except ValueError: return 0
T_h = {}
for t in teach: T_h[t.get('institution', '')] = T_h.get(t.get('institution', ''), 0) + hrs(t)
def base(title): return re.sub(r'\s*\([^)]*\)\s*$', '', str(title)).strip()
t_total = int(sum(T_h.values())); units = len({base(t.get('title')) for t in teach})
sup_all = phd + oth   # visiting researchers already left out of oth, as on the home page
phds = [r for r in phd if r.get('level') == 'PhD']
p_on = sum(ongoing(r) for r in phds); p_main = sum('main' in str(r.get('role', '')).lower() for r in phds)
def group(lv):
    lv = str(lv).lower()
    if 'intern' in lv or 'erasmus' in lv: return 'Internships and Erasmus'
    if lv == 'phd': return 'PhD'
    if lv.startswith('msc'): return 'MSc'
    if lv.startswith('bsc'): return 'BSc'
    return 'Postdoc, fellow and researchers'
G = Counter(group(r.get('level')) for r in sup_all)
order = ['BSc', 'MSc', 'PhD', 'Internships and Erasmus', 'Postdoc, fellow and researchers']
gtop = max(G.values())
gbars = ''.join(f'<div class="fb-row"><span class="fb-l">{H.escape(k)}</span><span class="fb-bar"><span style="width:{100*G[k]/gtop:.0f}%"></span></span><span class="fb-n">{G[k]}</span></div>' for k in order if G.get(k))
sp = lambda n: f"{n:,}".replace(',', ' ')
inst = ' and '.join(f'{sp(int(v))} h {H.escape(k)}' for k, v in sorted(T_h.items(), key=lambda kv: -kv[1]))
write('teaching_panel', f'''<section class="fund" aria-label="Teaching and supervision in figures">
<div class="fund-figs">
<div class="fund-fig fund-main"><span class="fund-n">{sp(t_total)}</span>
<span class="fund-l">hours of university teaching</span>
<span class="fund-s">{inst}, across {units} course units</span></div>
<div class="fund-fig"><span class="fund-n">{len(sup_all)}</span>
<span class="fund-l">supervisions, from BSc to postdoc</span>
<span class="fund-s">students, interns and researchers</span></div>
<div class="fund-fig"><span class="fund-n">{len(phds)}</span>
<span class="fund-l">PhD students</span>
<span class="fund-s">{p_on} ongoing, {len(phds) - p_on} completed; {p_main} as main supervisor</span></div>
</div>
<div class="fund-bars"><p class="fb-title">Supervisions by level</p>{gbars}</div>
</section>''')
print('teaching panel written')

# Teaching map (themes, hours, level, university) and slim timeline, from data/teaching.yml + data/teaching_themes.yml.
TH = yaml.safe_load(open('data/teaching_themes.yml', encoding='utf-8'))
theme_of = {u: i for i, th in enumerate(TH) for u in th['units']}
missing = sorted({base(t.get('title')) for t in teach} - set(theme_of))
if missing: raise SystemExit(f'Course units without a theme in data/teaching_themes.yml: {missing}')
def acad_years(y):  # "2019/2020" -> [2019]; "2020–2023" -> [2020, 2021, 2022] (academic years by start year)
    ys = [int(v) for v in re.findall(r'(?:19|20)\d\d', str(y))]
    return list(range(ys[0], max(ys[-1], ys[0] + 1))) if ys else []
U = {}
for t in teach:
    u = U.setdefault(base(t.get('title')), {'h': 0, 'lv': set(), 'inst': set(), 'yrs': set()})
    u['h'] += hrs(t); u['yrs'].update(acad_years(t.get('year')))
    c = str(t.get('courses', ''))
    if 'MSc' in c: u['lv'].add('MSc')
    if 'undergraduate' in c.lower() or 'BSc' in c: u['lv'].add('Undergraduate')
    u['inst'].add('USW' if 'South Wales' in str(t.get('institution')) else 'UC' if 'Coimbra' in str(t.get('institution')) else t.get('institution'))
th_h = [sum(U[n]['h'] for n in th['units'] if n in U) for th in TH]; th_top = max(th_h)
tags = lambda u: ''.join(f'<span class="tm-tag">{H.escape(x)}</span>' for x in sorted(u['lv'], reverse=True) + sorted(u['inst']))
tmap = ''
for i, th in enumerate(TH):
    rows = sorted((n for n in th['units'] if n in U), key=lambda n: -U[n]['h'])
    tmap += (f'<div class="tm-theme tm-c{i}"><div class="tm-head"><span class="tm-name">{H.escape(th["theme"])}</span>'
             f'<span class="tm-bar"><span style="width:{100*th_h[i]/th_top:.0f}%"></span></span><span class="tm-h">{sp(int(th_h[i]))} h</span></div><ul class="tm-units">'
             + ''.join(f'<li><span class="tm-u">{H.escape(n)}</span>{tags(U[n])}<span class="tm-uh">{sp(int(U[n]["h"]))} h</span></li>' for n in rows) + '</ul></div>')
allyrs = sorted({y for u in U.values() for y in u['yrs']}); yrs = list(range(allyrs[0], allyrs[-1] + 1))
order_u = sorted(U, key=lambda n: (theme_of[n], min(U[n]['yrs'])))
cols = f'--n: {len(yrs)}'
tl = f'<div class="tl-row tl-hdr" style="{cols}"><span></span>' + ''.join(f'<span>{str(y)[2:]}/{str(y+1)[2:]}</span>' for y in yrs) + '</div>'
for n in order_u:
    tl += (f'<div class="tl-row tm-c{theme_of[n]}" style="{cols}"><span class="tl-l">{H.escape(n)}</span>'
           + ''.join(f'<span class="tl-cell{" on" if y in U[n]["yrs"] else ""}"' + (f' title="{H.escape(n)}, {y}/{y+1}"' if y in U[n]['yrs'] else '') + '></span>' for y in yrs) + '</div>')
write('teaching_map', f'''<section class="tmap" aria-label="What I teach, by theme">
<h2>What I teach</h2>
{tmap}
<p class="tm-note">Hours summed over all years taught. USW: University of South Wales; UC: University of Coimbra.</p>
<div class="tl" aria-label="Course units by academic year"><p class="fb-title">When</p>{tl}</div>
</section>''')
print('teaching map written')

