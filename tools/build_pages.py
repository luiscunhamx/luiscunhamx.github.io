"""Write the list sections of the site (_gen/*.md) from data/*.yml. Run before `quarto render`."""
import yaml, os, re

def load(n):
    p = f'data/{n}.yml'
    return yaml.safe_load(open(p, encoding='utf-8')) or [] if os.path.exists(p) else []

def esc(s): return str(s).replace('*', r'\*').replace('_', r'\_') if s else ''
def bold_me(a): return re.sub(r'(Cunha, L(?:\.\s?F\.\s?N\.|\.(?:F\.N\.)?)?)', r'**\1**', esc(a)) if a else ''
def doi(d): return f' [doi:{d}](https://doi.org/{d})' if d else ''
def ystart(s): m = re.search(r'(19|20)\d\d', str(s)); return int(m.group()) if m else 0
def write(name, txt):
    os.makedirs('_gen', exist_ok=True)
    open(f'_gen/{name}.md', 'w', encoding='utf-8').write('<!-- Generated by tools/build_pages.py from data/*.yml. Do not edit. -->\n\n' + txt + '\n')

def cite(r):
    venue = esc(r.get('venue', ''))
    vol = ''.join(x for x in [f", {r['volume']}" if r.get('volume') else '', f"({r['issue']})" if r.get('issue') else '', f", {r['pages']}" if r.get('pages') else ''])
    link = doi(r.get('doi')) or (f" [link]({r['link']})" if r.get('link', '').startswith('http') else '')
    return f"{bold_me(r.get('authors'))} ({r.get('year','')}). {esc(str(r.get('title','')).rstrip('.'))}. *{venue}*{vol}.{link}"

def by_year(recs, fmt, key='year'):
    out, cur = [], None
    for r in sorted(recs, key=lambda r: -ystart(r.get(key, 0))):
        y = ystart(r.get(key, 0)) or 'Undated'
        if y != cur: out.append(f'\n### {y}\n'); cur = y
        out.append(f'- {fmt(r)}')
    return '\n'.join(out)

pubs = load('publications')
write('publications', f'{len(pubs)} peer-reviewed articles, newest first.\n' + by_year(pubs, cite)
      + '\n\n## Book chapters\n\n' + '\n'.join(f'- {cite(r)}' for r in load('chapters'))
      + '\n\n## Preprints\n\n' + '\n'.join(f'- {cite(r)}' for r in sorted(load('preprints'), key=lambda r: -ystart(r.get('year'))))
      + '\n\n## Reports and guidelines\n\n' + '\n'.join(f'- {cite(r)}' for r in sorted(load('reports'), key=lambda r: -ystart(r.get('year')))))

write('projects', '\n'.join(
    f"- **{esc(p['project'])}** ({p.get('years','')})  \n  {esc(p.get('role',''))}" + (f" · PI: {esc(p['pi'])}" if p.get('pi') else '')
    + (f" · {esc(p['funder'])}" if p.get('funder') else '')
    for p in sorted(load('projects'), key=lambda p: -ystart(p.get('years')))))

write('talks', by_year(load('talks'), lambda t: f"{esc(t['title'])}" + (f". {esc(t['event'])}" if t.get('event') else '') + (f", {esc(t['location'])}" if t.get('location') else '') + (f". [link]({t['link']})" if str(t.get('link','')).startswith('http') else '') + '.'))

def sup(r): return f"**{esc(r.get('name',''))}** ({esc(r.get('level',''))}, {r.get('years','')}). *{esc(r.get('title',''))}*. {esc(r.get('degree',''))}, {esc(r.get('institution',''))}. {esc(r.get('role',''))}."
write('supervision', '## Doctoral and postdoctoral\n\n' + '\n'.join(f'- {sup(r)}' for r in sorted(load('supervision_phd'), key=lambda r: -ystart(r.get('years'))))
      + '\n\n## Master’s and undergraduate\n\n' + '\n'.join(f'- {sup(r)}' for r in sorted(load('supervision_other'), key=lambda r: -ystart(r.get('years')))))

teach = load('teaching')
write('teaching', '| Academic year | Course unit | Programme(s) | Institution | Hours |\n|:--|:--|:--|:--|--:|\n' + '\n'.join(
    f"| {t.get('year','')} | {esc(t.get('title',''))} | {esc(t.get('courses',''))} | {esc(t.get('institution',''))} | {t.get('hours','')} |"
    for t in sorted(teach, key=lambda t: -ystart(t.get('year')))))

cv = ['## Positions\n'] + [f"- **{esc(e['position'])}**, {esc(e.get('institution',''))} ({e.get('period','')})" for e in load('experience')]
cv += ['\n## Coordination roles\n'] + [f"- {esc(r['role'])}, {esc(r.get('unit',''))} ({r.get('period','')})" for r in load('roles')]
cv += ['\n## Education\n'] + [f"- **{esc(e['degree'])}**, {esc(e.get('institution',''))} ({e.get('years','')})" + (f". *{esc(e['thesis'])}*" if e.get('thesis') else '') + (f" — {esc(e['honours'])}" if e.get('honours') else '') + (f" [link]({e['link']})" if str(e.get('link','')).startswith('http') else '') for e in load('education')]
cv += ['\n## Distinctions\n'] + [f"- {d.get('year','')} — {esc(d['title'])}, {esc(d.get('body',''))}" for d in sorted(load('distinctions'), key=lambda d: -ystart(d.get('year')))]
cv += ['\n## Memberships\n'] + [f"- {esc(m['organisation'])} — {esc(m.get('role',''))}" + (f" (since {m['since']})" if m.get('since') else '') for m in load('memberships')]
langs = [l for l in load('languages') if str(l.get('skill','')).startswith('Languages')]
cv += ['\n## Languages\n', ', '.join(f"{l['skill'].split('–')[-1].strip()} ({l.get('level','').lower()})" for l in langs)]
cv += ['\n## In the media\n'] + [f"- [{esc(o['title'])}]({o['link']}) — {esc(o.get('source',''))}" for o in load('outreach') if o.get('link')]
write('cv', '\n'.join(cv))
print('pages written')

# ---------- home page: headline figures, evidence blocks, selected work, output chart ----------
import html as H
M = yaml.safe_load(open('data/metrics.yml', encoding='utf-8')) or {}
phd = load('supervision_phd'); oth = load('supervision_other'); proj = load('projects')
led = [p for p in proj if re.match(r'(PI|WP Leader|Co-I)', str(p.get('role', '')))]
n_pubs = len(pubs) + len(load('chapters'))
def num(v): return v not in (None, '') and '[TO CONFIRM' not in str(v)
def eur(v): return f'€{v/1e6:.1f}M' if v >= 1e6 else f'€{v/1e3:.0f}k'

# Soil-core column: each horizon is one figure; thicker horizons = the figures that matter most to a panel.
layers = []
if num(M.get('h_index')): layers.append(('humus', str(M['h_index']), 'h-index', M.get('h_index_source')))
if num(M.get('citations')): layers.append(('topsoil', f"{int(M['citations']):,}".replace(',', ' '), 'citations', M.get('citations_source')))
layers.append(('topsoil', str(n_pubs), 'peer-reviewed papers and chapters', None))
if num(M.get('funding_total_eur')): layers.append(('subsoil', eur(M['funding_total_eur']), 'research funding', None))
layers.append(('subsoil', str(len(proj)), f'research projects, {len(led)} as PI, Co-I or WP leader', None))
layers.append(('parent', str(len(phd) + len(oth)), f'students and researchers supervised ({len(phd)} PhD or postdoc)', None))
if num(M.get('teaching_hours')): layers.append(('rock', f"{int(M['teaching_hours']):,}".replace(',', ' '), 'hours of university teaching', None))
core = ''.join(f'<div class="hz hz-{c}"><span class="hz-n">{H.escape(n)}</span><span class="hz-l">{H.escape(l)}</span></div>' for c, n, l, s in layers)
write('core', f'<div class="core" aria-label="Career in figures">{core}</div>\n<p class="core-note">Figures as of {M.get("as_of","")}. Sources: CV and publication databases.</p>')

# Output per year (papers), as a small inline SVG.
from collections import Counter
cnt = Counter(ystart(p.get('year')) for p in pubs if ystart(p.get('year')))
years = list(range(min(cnt), max(cnt) + 1)); mx = max(cnt.values()); W, Hh, bw = 640, 120, 640 / len(years)
bars = ''.join(f'<rect x="{i*bw+2:.1f}" y="{Hh-18-(cnt.get(y,0)/mx)*(Hh-30):.1f}" width="{bw-4:.1f}" height="{(cnt.get(y,0)/mx)*(Hh-30):.1f}"><title>{y}: {cnt.get(y,0)}</title></rect>' for i, y in enumerate(years))
ticks = ''.join(f'<text x="{i*bw+bw/2:.1f}" y="{Hh-4}">{str(y)[2:]}</text>' for i, y in enumerate(years) if y % 2 == 0)
write('chart', f'<figure class="out-chart"><svg viewBox="0 0 {W} {Hh}" role="img" aria-label="Peer-reviewed papers per year, {years[0]} to {years[-1]}">{bars}{ticks}</svg><figcaption>Peer-reviewed papers per year, {years[0]}–{years[-1]}.</figcaption></figure>')

sel = yaml.safe_load(open('data/selected.yml', encoding='utf-8')) or []
bydoi = {p.get('doi'): p for p in pubs}
write('selected', '\n'.join(f'- {cite(bydoi[d])}' for d in sel if d in bydoi))
print('home page written')
